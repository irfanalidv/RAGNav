@pytest.mark.parametrize(
    "argv",
    [
        ["vectorless-pdf", "--print-hits"],
        ["hybrid-pdf", "--print-hits"],
        ["agentic-pdf", "--max-steps", "1"],
        ["paper-pdf", "--no-vectors", "--print-hits"],
        ["paper-pdf", "--no-vectors", "--cited"],
    ],
    ids=lambda a: " ".join(a),
)
def test_cli_commands_offline(argv, offline_cli, tmp_path, capsys) -> None:
    from ragnav.cli import main

    common = ["--pdf-url", "https://example.org/x.pdf", "--query", "What is fused?"]
    extra = ["--cache-path", str(tmp_path / "x.pdf"), "--cache-db", str(tmp_path / "c.db")]
    assert main([*argv, *common, *extra]) == 0
    out = capsys.readouterr().out
    assert "[fake-llm:" in out or "[[pdf:" in out
    if "--print-hits" in argv:
        assert '"block_id"' in out


def test_cli_version(capsys) -> None:
    from ragnav import __version__
    from ragnav.cli import main

    with pytest.raises(SystemExit) as exc:
        main(["--version"])
    assert exc.value.code == 0
    assert __version__ in capsys.readouterr().out
