"""PDF ingestion, PaperRAG, pipelines, and the CLI on a PDF generated in-process.

No network: ``download_pdf`` is patched to return the generated bytes and the Mistral
client is replaced with ``FakeLLMClient``.
"""

from __future__ import annotations

import re

import pytest

pymupdf = pytest.importorskip("pymupdf")

from ragnav.ingest.pdf import (  # noqa: E402
    PdfIngestOptions,
    ingest_pdf_bytes,
    ingest_pdf_bytes_graph,
    ingest_pdf_bytes_paper,
    ingest_pdf_file,
    ingest_pdf_file_graph,
    ingest_pdf_file_paper,
)
from ragnav.llm.fake import FakeLLMClient  # noqa: E402


class CitingLLM(FakeLLMClient):
    """FakeLLMClient that answers citation prompts with a valid ``[[block_id]]`` citation."""

    def chat(self, *, messages, model=None, temperature=0):  # type: ignore[no-untyped-def]
        prompt = messages[-1]["content"]
        match = re.search(r"BLOCK_ID=(\S+)\s+PAGE=", prompt)
        if match:
            block_id = match.group(1)
            return f"Scores are fused with reciprocal rank fusion [[{block_id}]]."
        return super().chat(messages=messages, model=model, temperature=temperature)


PAGE_1 = [
    "1 Introduction",
    "We study retrieval for long documents. Results are shown in Figure 1.",
    "See Table 2 and Appendix A for details.",
    "",
    "Figure 1: Recall at k for BM25 and hybrid retrieval.",
]
PAGE_2 = [
    "2 Method",
    "Hybrid retrieval fuses BM25 and dense scores with reciprocal rank fusion.",
    "",
    "Table 2: Ablation of fusion weights.",
    "",
    "Appendix A",
    "Extra experiments on scientific papers.",
]


def make_pdf(pages: list[list[str]]) -> bytes:
    doc = pymupdf.open()
    for lines in pages:
        page = doc.new_page()
        y = 72
        for line in lines:
            if line:
                page.insert_text((72, y), line, fontsize=10)
            y += 14
    data = doc.tobytes()
    doc.close()
    return data


@pytest.fixture(scope="module")
def pdf_bytes() -> bytes:
    return make_pdf([PAGE_1, PAGE_2])


def test_ingest_pdf_bytes_one_block_per_page(pdf_bytes: bytes) -> None:
    doc, blocks = ingest_pdf_bytes(pdf_bytes, name="paper.pdf", metadata={"k": "v"})
    assert doc.doc_id == "pdf:paper.pdf" and doc.metadata["k"] == "v"
    assert [b.anchors["page"] for b in blocks] == [1, 2]
    assert "Introduction" in blocks[0].text
    _, first_only = ingest_pdf_bytes(pdf_bytes, opts=PdfIngestOptions(max_pages=1))
    assert len(first_only) == 1


def test_ingest_pdf_paper_mode_links_cross_references(pdf_bytes: bytes) -> None:
    doc, blocks, edges = ingest_pdf_bytes_paper(pdf_bytes, name="paper.pdf")
    assert doc.metadata["mode"] == "paper"
    by_id = {b.block_id: b for b in blocks}
    headings = [b.text for b in blocks if b.type == "heading"]
    assert any("Introduction" in h for h in headings)
    captions = {b.metadata.get("caption_kind") for b in blocks}
    assert {"figure", "table"} <= captions
    link_targets = {by_id[e.dst].text.split(":")[0] for e in edges if e.type == "link_to"}
    assert "Figure 1" in link_targets and "Table 2" in link_targets
    assert any(e.type == "next" for e in edges)
    # paper_mode via the plain entrypoint returns the same blocks
    _, same = ingest_pdf_bytes(pdf_bytes, name="paper.pdf", opts=PdfIngestOptions(paper_mode=True))
    assert [b.block_id for b in same] == [b.block_id for b in blocks]


def test_ingest_pdf_graph_and_file_variants(pdf_bytes: bytes, tmp_path) -> None:
    path = tmp_path / "doc.pdf"
    path.write_bytes(pdf_bytes)
    doc, blocks = ingest_pdf_file(str(path))
    assert doc.doc_id == "pdf:doc.pdf" and len(blocks) == 2
    pdoc, pblocks, _ = ingest_pdf_file_paper(str(path))
    assert pdoc.doc_id == "pdf:doc.pdf" and len(pblocks) > 2

    g = ingest_pdf_bytes_graph(pdf_bytes, name="g.pdf")
    assert len(g.blocks) == 2 and any(e.type == "next" for e in g.edges)
    gp = ingest_pdf_file_graph(str(path), opts=PdfIngestOptions(paper_mode=True))
    assert any(e.type == "link_to" for e in gp.edges)


def test_paper_rag_offline(pdf_bytes: bytes, monkeypatch) -> None:
    from ragnav.papers import PaperRAG, PaperRAGConfig

    cfg = PaperRAGConfig(build_vectors=False, top_pages=2, k_final=5)
    paper = PaperRAG.from_pdf_bytes(pdf_bytes, llm=CitingLLM(), pdf_name="p.pdf", cfg=cfg)
    res = paper.retrieve("How are BM25 and dense scores fused?", cfg=cfg)
    assert res.blocks and any("reciprocal rank fusion" in b.text for b in res.blocks)
    assert paper.answer("What is fused?", cfg=cfg).startswith("[fake-llm:")
    cited = paper.answer_cited("What is fused?", cfg=cfg)
    assert cited.endswith("]].") and "[[pdf:p.pdf#" in cited

    monkeypatch.setattr("ragnav.papers.rag.download_pdf", lambda url, **kw: pdf_bytes)
    from_url = PaperRAG.from_pdf_url("https://example.org/p.pdf", llm=FakeLLMClient(), cfg=cfg)
    assert from_url.doc_id == "pdf:paper.pdf"


def test_vectorless_and_hybrid_pipelines(pdf_bytes: bytes, monkeypatch, tmp_path) -> None:
    from ragnav.pipelines import (
        HybridRagConfig,
        hybrid_answer,
        hybrid_rag_pdf_url,
        vectorless_answer,
        vectorless_rag_pdf_url,
    )

    monkeypatch.setattr("ragnav.pipelines.vectorless.download_pdf", lambda url, **kw: pdf_bytes)
    monkeypatch.setattr("ragnav.pipelines.hybrid.download_pdf", lambda url, **kw: pdf_bytes)
    llm = FakeLLMClient()

    retrieve, doc_id = vectorless_rag_pdf_url(pdf_url="u", llm=llm, cache_path=None)
    assert doc_id == "pdf:document.pdf"
    assert retrieve("reciprocal rank fusion")
    assert vectorless_answer(query="q", retrieve_fn=retrieve, llm=llm).startswith("[fake-llm:")

    retriever, hdoc = hybrid_rag_pdf_url(pdf_url="u", llm=llm, cache_path=tmp_path / "h.pdf")
    assert hdoc == "pdf:h.pdf"
    answer = hybrid_answer(query="fusion", retriever=retriever, llm=llm, cfg=HybridRagConfig())
    assert answer.startswith("[fake-llm:")


